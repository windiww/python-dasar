# Operator (Bab #6)
a = 15
b = 4

# Operator aritmatika
print("Penjumlahan (a + b):", a + b)
print("Pembagian bulat (a // b):", a // b)
print("Sisa bagi / modulus (a % b):", a % b)
print("Pangkat (a ** 2):", a ** 2)

# Operator perbandingan
print("Apakah a > b?:", a > b)
print("Apakah a == b?:", a == b)

# Operator logika
lulus_tugas = True
lulus_absen = True
print("Lulus mata kuliah:", lulus_tugas and lulus_absen)
print("Perlu remedial:", not (lulus_tugas and lulus_absen))
