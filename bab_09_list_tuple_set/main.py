# List, Tuple, dan Set (Bab #9)

# 1. List (mutable)
buah_list = ["Apel", "Jeruk", "Mangga"]
buah_list.append("Pisang")
print("List buah:", buah_list)

# 2. Tuple (immutable)
koordinat = (106.8456, -6.2088)
print("Tuple koordinat:", koordinat)

# 3. Set (unik, otomatis menghapus duplikat)
hobi_set = {"Coding", "Membaca", "Coding", "Musik"}
print("Set hobi:", hobi_set)
